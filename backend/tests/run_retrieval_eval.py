"""Compare BM25-only, dense-only and hybrid (RRF) retrieval on the labelled evaluation set. No LLM involved.

Usage (from backend/):  python tests/run_retrieval_eval.py
Writes ../outputs/retrieval_evaluation.md and prints the same tables.
Metrics (binary relevance, per query, then averaged):
  Recall@k = |relevant in top k| / |relevant|      MRR@10 = 1 / rank of first relevant (0 if none in top 10)
  nDCG@10  = DCG / ideal DCG, DCG = sum rel_i / log2(i + 1)
"""
from __future__ import annotations

import json
import math
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.stdout.reconfigure(encoding="utf-8")

from app.config import get_settings  # noqa: E402
from app.rag.retriever import get_retriever, retrieve  # noqa: E402

EVAL_SET = Path(__file__).with_name("retrieval_eval_set.json")
OUT = Path(__file__).resolve().parents[2] / "outputs" / "retrieval_evaluation.md"
MODES = ["bm25", "dense", "hybrid"]


def metrics(ranked: list[str], relevant: set[str]) -> dict:
    def recall(k):
        return len(set(ranked[:k]) & relevant) / len(relevant)
    first = next((i for i, c in enumerate(ranked[:10], start=1) if c in relevant), None)
    dcg = sum(1 / math.log2(i + 1) for i, c in enumerate(ranked[:10], start=1) if c in relevant)
    idcg = sum(1 / math.log2(i + 1) for i in range(1, min(len(relevant), 10) + 1))
    return {"recall@5": recall(5), "recall@10": recall(10), "mrr@10": 1 / first if first else 0.0,
            "ndcg@10": dcg / idcg, "first_rank": first}


def avg(rows: list[dict], key: str) -> float:
    return sum(r[key] for r in rows) / len(rows)


def run() -> str:
    data = json.loads(EVAL_SET.read_text(encoding="utf-8"))
    queries = data["queries"]
    valid = {c["id"] for c in get_retriever().chunks}
    for q in queries:
        missing = set(q["relevant"]) - valid
        assert not missing, f"{q['id']}: unknown chunk IDs {missing}"

    per = {m: [] for m in MODES}
    for q in queries:
        for m in MODES:
            ranked = [s["chunk_id"] for s in retrieve(q["query"], top_k=10, mode=m)]
            per[m].append({**metrics(ranked, set(q["relevant"])), "id": q["id"], "lang": q["lang"]})

    s = get_settings()
    L = [f"# Retrieval evaluation: BM25 vs dense vs hybrid (RRF)\n",
         f"Generated by `backend/tests/run_retrieval_eval.py` on {datetime.now():%Y-%m-%d %H:%M}. No LLM involved.\n",
         f"- Corpus: {len(valid)} chunks from official Indian consumer-law documents",
         f"- Queries: {len(queries)} ({sum(q['lang']=='en' for q in queries)} English, "
         f"{sum(q['lang']=='hi' for q in queries)} Hindi, {sum(q['lang']=='hinglish' for q in queries)} Hinglish), "
         f"relevance labels in `backend/tests/retrieval_eval_set.json`",
         f"- Dense: `{s.embedding_model}`, FAISS IndexFlatIP on normalised vectors; hybrid: RRF k={s.rrf_k}, "
         f"{s.rag_candidates} candidates per ranker. No category hints used here.\n",
         "## Overall\n", "| Method | Recall@5 | Recall@10 | MRR@10 | nDCG@10 |", "|---|---|---|---|---|"]
    for m in MODES:
        r = per[m]
        L.append(f"| {m} | {avg(r,'recall@5'):.3f} | {avg(r,'recall@10'):.3f} | {avg(r,'mrr@10'):.3f} | {avg(r,'ndcg@10'):.3f} |")
    L += ["\n## By query language (nDCG@10)\n", "| Language | n | BM25 | Dense | Hybrid |", "|---|---|---|---|---|"]
    for lang in ["en", "hi", "hinglish"]:
        idx = [i for i, q in enumerate(queries) if q["lang"] == lang]
        vals = [sum(per[m][i]["ndcg@10"] for i in idx) / len(idx) for m in MODES]
        L.append(f"| {lang} | {len(idx)} | " + " | ".join(f"{v:.3f}" for v in vals) + " |")
    L += ["\n## Per query: rank of first relevant chunk (— = not in top 10)\n",
          "| ID | Lang | Type | BM25 | Dense | Hybrid | Query |", "|---|---|---|---|---|---|---|"]
    for i, q in enumerate(queries):
        ranks = [per[m][i]["first_rank"] or "—" for m in MODES]
        L.append(f"| {q['id']} | {q['lang']} | {q['type']} | {ranks[0]} | {ranks[1]} | {ranks[2]} | {q['query']} |")
    better = sum(per["hybrid"][i]["ndcg@10"] > max(per["bm25"][i]["ndcg@10"], per["dense"][i]["ndcg@10"]) + 1e-9 for i in range(len(queries)))
    worse = [queries[i]["id"] for i in range(len(queries))
             if per["hybrid"][i]["ndcg@10"] + 1e-9 < max(per["bm25"][i]["ndcg@10"], per["dense"][i]["ndcg@10"])]
    L.append(f"\nHybrid beats both single methods (nDCG@10) on {better}/{len(queries)} queries; "
             f"it is worse than the better single method on: {', '.join(worse) or 'none'}.")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    report = run()
    OUT.write_text(report, encoding="utf-8")
    print(report)
